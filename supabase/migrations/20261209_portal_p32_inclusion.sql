-- =====================================================================================
--  P32 «أَثَر للجميع» — بوابة تتكيّف مع من يستخدمها، لا بوابة منفصلة
--  1) portal_access_profiles   ملف «أَثَر على مقاسي»: احتياجات بكلمات الحاجة (لا تشخيص) — خاصّ بصاحبه
--  2) portal_access_texts      «نسخة أبسط» من نصوص البوابة: يقترحها الذكاء الاصطناعي ويعتمدها الطاقم
--  3) portal_access_reports    «أخبرنا بعائق» — بلاغات الوصول (مجهولة أو بهوية) وحالتها
--  4) programs.access_features  ما يوفّره البرنامج فعلًا للجميع (ترجمة حيّة · لغة إشارة · مواد مقروءة آليًا …)
--  5) أفق الجهة: نوع عهد جديد 'inclusion' («تعهّد الشمول»)
--  السياسة: الملف حسّاس بمعنى نظام حماية البيانات الشخصية؛ لا يُقرأ إلا بصاحبه (RLS) أو بالخدمة لأجل إحصاءات مجمَّعة k≥5.
--  آمن لإعادة التشغيل (idempotent).
-- =====================================================================================

-- 1) ملف «أَثَر على مقاسي»
create table if not exists public.portal_access_profiles (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  email        text not null,
  needs        text[] not null default '{}',
  helps_ar     text,                                   -- «ما يساعدني» بكلمات صاحبه (اختياري · ≤ 400 حرفًا)
  share_staff  boolean not null default false,         -- يسمح للطاقم برؤية الاحتياجات عند تنسيق برنامج يلتحق به
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint portal_access_profiles_needs_chk check (coalesce(array_length(needs, 1), 0) <= 12),
  constraint portal_access_profiles_helps_chk check (helps_ar is null or char_length(helps_ar) <= 400)
);
create index if not exists portal_access_profiles_email_idx on public.portal_access_profiles (lower(email));
create index if not exists portal_access_profiles_needs_idx on public.portal_access_profiles using gin (needs);

alter table public.portal_access_profiles enable row level security;
drop policy if exists pap_self_select on public.portal_access_profiles;
drop policy if exists pap_self_insert on public.portal_access_profiles;
drop policy if exists pap_self_update on public.portal_access_profiles;
drop policy if exists pap_self_delete on public.portal_access_profiles;
create policy pap_self_select on public.portal_access_profiles for select using (auth.uid() = user_id);
create policy pap_self_insert on public.portal_access_profiles for insert with check (auth.uid() = user_id);
create policy pap_self_update on public.portal_access_profiles for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy pap_self_delete on public.portal_access_profiles for delete using (auth.uid() = user_id);
grant select, insert, update, delete on public.portal_access_profiles to authenticated;

-- 2) «نسخة أبسط» — نص واحد لكل مصدر؛ لا يُعرض للجمهور قبل اعتماد بشري
create table if not exists public.portal_access_texts (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  source        text not null,                         -- program_intro | program_objectives | daily_case | page
  source_id     text not null,                         -- معرّف البرنامج/الموقف أو مسار الصفحة
  original_hash text not null,                         -- بصمة النص الأصلي — إن تغيّر الأصل بطلت النسخة
  simple_ar     text not null,
  status        text not null default 'pending',
  requested_by  uuid references auth.users(id) on delete set null,
  approved_by   uuid references auth.users(id) on delete set null,
  approved_at   timestamptz,
  model         text,
  note_ar       text,
  constraint portal_access_texts_status_chk check (status in ('pending','approved','rejected')),
  constraint portal_access_texts_source_chk check (source in ('program_intro','program_objectives','daily_case','page')),
  constraint portal_access_texts_len_chk check (char_length(simple_ar) between 10 and 6000),
  constraint portal_access_texts_uq unique (source, source_id)
);
alter table public.portal_access_texts enable row level security;
drop policy if exists pat_public_read on public.portal_access_texts;
create policy pat_public_read on public.portal_access_texts for select using (status = 'approved');
grant select on public.portal_access_texts to anon, authenticated;

-- 3) بلاغات الوصول
create table if not exists public.portal_access_reports (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  page        text not null,
  text_ar     text not null,
  contact     text,                                    -- اختياري — بريد للرد
  user_id     uuid references auth.users(id) on delete set null,
  status      text not null default 'open',
  staff_note  text,
  closed_at   timestamptz,
  constraint portal_access_reports_status_chk check (status in ('open','fixed','wontfix')),
  constraint portal_access_reports_text_chk check (char_length(text_ar) between 5 and 2000)
);
create index if not exists portal_access_reports_status_idx on public.portal_access_reports (status, created_at desc);
alter table public.portal_access_reports enable row level security;   -- الكتابة والقراءة بالخدمة فقط (عبر /api/inclusion)

-- 4) ما يوفّره البرنامج للجميع
alter table public.programs add column if not exists access_features text[] not null default '{}';
create index if not exists programs_access_features_idx on public.programs using gin (access_features);

-- 5) أفق الجهة: «تعهّد الشمول»
alter table public.portal_org_horizon_pledges drop constraint if exists portal_org_horizon_pledges_kind_check;
alter table public.portal_org_horizon_pledges add constraint portal_org_horizon_pledges_kind_check
  check (kind in ('council','missions','daily','levels','attestations','yearbook','inclusion'));

-- 6) تحديث updated_at
create or replace function public.portal_touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists portal_access_profiles_touch on public.portal_access_profiles;
create trigger portal_access_profiles_touch before update on public.portal_access_profiles for each row execute function public.portal_touch_updated_at();
drop trigger if exists portal_access_texts_touch on public.portal_access_texts;
create trigger portal_access_texts_touch before update on public.portal_access_texts for each row execute function public.portal_touch_updated_at();

-- =====================================================================================
--  تشخيص (المتوقَّع بعد التشغيل الأول: 3 جداول · 1 عمود · 1 قيد يحوي inclusion)
-- =====================================================================================
select
  (select count(*) from information_schema.tables where table_schema = 'public' and table_name in ('portal_access_profiles','portal_access_texts','portal_access_reports')) as tables_3,
  (select count(*) from information_schema.columns where table_schema = 'public' and table_name = 'programs' and column_name = 'access_features') as column_1,
  (select count(*) from pg_constraint where conname = 'portal_org_horizon_pledges_kind_check' and pg_get_constraintdef(oid) like '%inclusion%') as pledge_kind_1,
  (select count(*) from pg_policies where tablename = 'portal_access_profiles') as policies_4;

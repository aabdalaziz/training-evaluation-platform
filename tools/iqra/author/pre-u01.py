def lcards(key, extra_words=None):
    """بطاقات: حروف الحلقة الجديدة (مع مثالين من كلمات الحلقة) + كلمات حتى 16."""
    out = []
    for g in NEW[key]:
        n, img, i, m, f = LETTERS[g]
        exs = [w for w, _ in W[key] if g in glyphs(w)][:2]
        forms = f'{i} {m} {f}' if g != 'ة' else 'ة ـة'
        hk = f' · {g}\u064E {g}\u064F {g}\u0650' if g not in 'اة' else ''
        out.append(card(g, f'{n} · {forms}{hk}', ' · '.join(exs)))
    for w, img in W[key]:
        if len(out) >= 16: break
        out.append(card(w, ' ، '.join(NAME[g] for g in glyphs(w)), ''))
    return out[:16]


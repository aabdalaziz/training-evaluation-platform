def lcards(key, letters=None):
    out = []
    for g in (NEW[key] if letters is None else letters):
        n, img, i, m, f = LETTERS[g]
        exs = [w for w, _ in W[key] if g in glyphs(w)][:2]
        forms = f'{i} {m} {f}' if g != 'ء' else 'أ ؤ ئ ء'
        hk = f' · {g}\u064E {g}\u064F {g}\u0650' if g not in 'اةء' else (' · أَ أُ إِ' if g == 'ء' else '')
        out.append(card(g, f'{n} · {forms}{hk}', ' · '.join(exs)))
    for w, img in W[key]:
        if len(out) >= 16: break
        out.append(card(w, ' ، '.join(NAME[g] for g in glyphs(w)), ''))
    return out[:16]

